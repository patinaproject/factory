"""Posts one round of a triage card's questions to its Linear agent session.

The `blocker-order` hook calls `linear_triage_round` by name after it parks the card in `scheduled`, so the
round is posted only once the card waits. The tool's `check_fn` always fails, so Hermes leaves it out of
every model's tool list, while `registry.dispatch` never calls the check and still reaches it by name.
"""
from __future__ import annotations

import json
import logging
import re
import threading
from typing import Any, Callable, Optional

from . import blocks, linear

logger = logging.getLogger(__name__)

NAME = "linear_triage_round"
# The hook parks and then posts inside Hermes' 30 s transform_tool_result limit; a post still open at this
# bound is reported as unknown, because it may have landed.
ROUND_TIMEOUT_SECONDS = 20.0
POSTED, FAILED, UNKNOWN = "posted", "failed", "unknown"
TRIAGE_DISCLAIMER = "> *This was generated by AI during triage.*"
PROFILE_URL = re.compile(r"https://linear\.app/[^/\s]+/profiles/[\w-]+(?:\.[\w-]+)*")
PROFILE_URL_AND_SPACE = re.compile(PROFILE_URL.pattern + r"[ \t]*")
NEEDS_INPUT_MARKER = re.compile(r"^\s*Needs input:[ \t]*")
MENTION_REPLY = "Triage needs your answer to the questions above."

SCHEMA = {
    "name": NAME,
    "description": "Post a parked triage card's round of questions to its Linear agent session. Only the blocker-order hook calls it.",
    "parameters": {
        "type": "object",
        "properties": {
            "task_id": {"type": "string", "description": "The triage card."},
            "board": {"type": "string", "description": "The card's board."},
            "reason": {"type": "string", "description": "Claude's `Needs input:` result, without the park's marker."},
        },
        "required": ["task_id", "board", "reason"],
    },
}


def round_activity(reason: Optional[str], redact: Callable[[str], str]) -> dict:
    # Redact before truncating: a cut can split a secret into a piece no pattern recognizes.
    text = blocks.clip(_questions(reason, redact) or "no questions given", blocks.TEXT_LIMIT)
    return linear.activity_content("elicitation", f"{TRIAGE_DISCLAIMER}\n\n{text}\n\nReply here to answer.")


def mention_reply(reason: Optional[str], redact: Callable[[str], str]) -> Optional[str]:
    """Linear notifies for a mention in a comment, never for one in an activity."""
    people = list(dict.fromkeys(PROFILE_URL.findall(blocks.questions(reason, redact))))
    return f"{' '.join(people)} {MENTION_REPLY}" if people else None


def _questions(reason: Optional[str], redact: Callable[[str], str]) -> str:
    # The reply mentions each person; a URL left in the elicitation renders as a second, non-notifying @name.
    lines = []
    for line in blocks.questions(reason, redact).splitlines():
        text = PROFILE_URL_AND_SPACE.sub("", NEEDS_INPUT_MARKER.sub("", line)).rstrip()
        # Drop a line that held only a marker or URLs, and a blank line that would now double another.
        if text or (not line.strip() and lines and lines[-1]):
            lines.append(text)
    return "\n".join(lines).strip()


def _twice(step: Callable[[], Any]) -> None:
    try:
        step()
    except Exception as error:
        logger.warning("linear-agent-session: a triage round call failed (%s); retrying once", type(error).__name__)
        step()


def make_handler(
    get_client: Callable[[], linear.LinearClient],
    load: Callable[[str, Optional[str]], blocks.Card] = blocks.load_card,
    redact: Callable[[str], str] = blocks.hermes_redact,
) -> Callable[..., str]:
    def post(task_id: str, board: Optional[str], reason: Optional[str], outcome: dict) -> None:
        try:
            agent_session = blocks.session_id(load(task_id, board).body)
            if agent_session is None:
                outcome.update(outcome=FAILED, error=f"card {task_id} has no linear_agent_session_id")
                return
            client = get_client()
            _twice(lambda: client.create_activity(agent_session, round_activity(reason, redact)))
            reply = mention_reply(reason, redact)
            if reply is not None:
                _twice(lambda: client.reply_in_session(agent_session, reply))
            outcome["outcome"] = POSTED
            blocks.close_older_sessions(client, agent_session)
        except Exception as error:
            outcome.update(outcome=FAILED, error=type(error).__name__)
            logger.warning("linear-agent-session: posting the triage round of card %s failed: %s", task_id, type(error).__name__)

    def handle(args: dict, **_: Any) -> str:
        task_id = args.get("task_id")
        outcome: dict = {}
        worker = threading.Thread(target=post, args=(task_id, args.get("board"), args.get("reason"), outcome), daemon=False)
        worker.start()
        worker.join(ROUND_TIMEOUT_SECONDS)
        settled = dict(outcome)
        if "outcome" not in settled:
            logger.warning("linear-agent-session: posting the triage round of card %s is still running; moving on", task_id)
            return json.dumps({"outcome": UNKNOWN})
        return json.dumps(settled)

    return handle
